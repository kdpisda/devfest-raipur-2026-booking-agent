"""
Chai & Code Cowork — a tiny, *prepared* CRM + booking API for the workshop.

You do NOT edit this file during the workshop. It plays the part of the
"real business system" your agent talks to over HTTP.

It also has a CHAOS switch, because real systems lie, time out and fail:
    none        everything behaves
    fail        POST /bookings returns 503
    ghost       POST /bookings says 201 Created... but stores nothing
    wrong_room  stores the booking in a DIFFERENT room than requested
    pending     stores the booking as pending_payment, but answers "confirmed"
    slow        stores the booking, then responds after 6s (client times out)

All data is fictional.
"""
from __future__ import annotations

import datetime as dt
import secrets
import sqlite3
import threading
import time
from pathlib import Path

from fastapi import FastAPI, Header, HTTPException, Query
from fastapi.responses import HTMLResponse
from pydantic import BaseModel

IST = dt.timezone(dt.timedelta(hours=5, minutes=30), "IST")
OPEN, CLOSE = "08:00", "22:00"
OFFER_TTL_MIN = 20
CHAOS_MODES = ["none", "fail", "ghost", "wrong_room", "pending", "slow"]

DB_PATH = Path(__file__).resolve().parent.parent / "data" / "crm.sqlite3"
_lock = threading.RLock()
_state = {"chaos": "none"}


def today() -> dt.date:
    return dt.datetime.now(IST).date()


def _conn() -> sqlite3.Connection:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    c = sqlite3.connect(DB_PATH, check_same_thread=False)
    c.row_factory = sqlite3.Row
    return c


