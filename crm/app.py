# ---------------------------------------------------------------- helpers
def _t(s: str) -> int:
    try:
        h, m = s.split(":")
        return int(h) * 60 + int(m)
    except Exception:
        raise HTTPException(422, f"time must be HH:MM (24h), got {s!r}")


def _hm(minutes: int) -> str:
    return f"{minutes // 60:02d}:{minutes % 60:02d}"


def _validate_slot(date: str, start: str, end: str) -> dt.date:
    try:
        d = dt.date.fromisoformat(date)
    except ValueError:
        raise HTTPException(422, f"date must be YYYY-MM-DD, got {date!r}")
    if d < today():
        raise HTTPException(422, "date is in the past")
    s, e = _t(start), _t(end)
    if s >= e:
        raise HTTPException(422, "start_time must be before end_time")
    if s < _t(OPEN) or e > _t(CLOSE):
        raise HTTPException(422, f"we are open {OPEN}-{CLOSE} IST")
    if d == today() and s <= dt.datetime.now(IST).hour * 60 + dt.datetime.now(IST).minute:
        raise HTTPException(422, "start_time has already passed today")
    return d


def _is_free(c, room_id: str, date: str, s: int, e: int) -> bool:
    rows = c.execute(
        "SELECT start_time, end_time FROM bookings WHERE room_id=? AND date=? "
        "AND status IN ('confirmed','pending_payment')",
        (room_id, date),
    ).fetchall()
    return all(e <= _t(r["start_time"]) or s >= _t(r["end_time"]) for r in rows)


def _price(rate: int, minutes: int, plan: str) -> int:
    base = rate * minutes / 60
    return int(round(base * (0.8 if plan == "member" else 1.0)))


def _customer(c, customer_id: str):
    row = c.execute("SELECT * FROM customers WHERE id=?", (customer_id,)).fetchone()
    if not row:
        raise HTTPException(404, "customer not found")
    return row


# ---------------------------------------------------------------- API
app = FastAPI(title="Chai & Code Cowork CRM (workshop)")


@app.get("/health")
def health():
    return {"ok": True, "chaos": _state["chaos"], "today": today().isoformat()}


@app.get("/customers/lookup")
def lookup_customer(phone: str):
    with _lock, _conn() as c:
        row = c.execute("SELECT * FROM customers WHERE phone=?", (phone,)).fetchone()
    if not row:
        raise HTTPException(404, "no customer with that phone")
    return dict(row)


@app.get("/rooms/availability")
def availability(
    customer_id: str, date: str, start_time: str, end_time: str, capacity: int = Query(ge=1)
):
    d = _validate_slot(date, start_time, end_time)
    s, e = _t(start_time), _t(end_time)
    with _lock, _conn() as c:
        cust = _customer(c, customer_id)
        rooms = c.execute(
            "SELECT * FROM rooms WHERE capacity>=? ORDER BY capacity", (capacity,)
        ).fetchall()
        if not rooms:
            return {"options": [], "alternatives": [], "note": "no room fits that many people"}
        options, busy = [], []
        exp = (dt.datetime.now(IST) + dt.timedelta(minutes=OFFER_TTL_MIN)).isoformat()
        for r in rooms:
            if _is_free(c, r["id"], d.isoformat(), s, e):
                oid = "OF-" + secrets.token_hex(3).upper()
                price = _price(r["hourly_rate_inr"], e - s, cust["plan"])
                c.execute(
                    "INSERT INTO offers VALUES (?,?,?,?,?,?,?,?)",
                    (oid, customer_id, r["id"], d.isoformat(), start_time, end_time, price, exp),
                )
                options.append(
                    {"offer_id": oid, "room_id": r["id"], "room": r["name"], "capacity": r["capacity"],
                     "amenities": r["amenities"], "date": d.isoformat(),
                     "start_time": start_time, "end_time": end_time, "price_inr": price,
                     "member_discount_applied": cust["plan"] == "member"}
                )
            else:
                busy.append(r)
        alternatives = []
        if not options:  # suggest nearby slots of the same length in the best-fitting room
            r = rooms[0]
            for shift in (60, -60, 120, -120, 180, 240):
                ns, ne = s + shift, e + shift
                if ns >= _t(OPEN) and ne <= _t(CLOSE) and _is_free(c, r["id"], d.isoformat(), ns, ne):
                    alternatives.append({"room": r["name"], "start_time": _hm(ns), "end_time": _hm(ne)})
                if len(alternatives) == 2:
                    break
    return {"options": options, "alternatives": alternatives,
            "unavailable_rooms": [b["name"] for b in busy]}


class BookingIn(BaseModel):
    customer_id: str
    offer_id: str


@app.post("/bookings", status_code=201)
def create_booking(body: BookingIn, idempotency_key: str | None = Header(default=None)):
    mode = _state["chaos"]
    if mode == "fail":
        raise HTTPException(503, "booking service unavailable")
    with _lock, _conn() as c:
        if idempotency_key:
            prev = c.execute("SELECT * FROM bookings WHERE idempotency_key=?",
                             (idempotency_key,)).fetchone()
            if prev:
                return dict(prev)  # same request again -> same booking, no duplicate
        off = c.execute("SELECT * FROM offers WHERE id=?", (body.offer_id,)).fetchone()
        if not off:
            raise HTTPException(404, "unknown offer_id")
        if off["customer_id"] != body.customer_id:
            raise HTTPException(403, "offer belongs to another customer")
        if off["expires_at"] < dt.datetime.now(IST).isoformat():
            raise HTTPException(410, "offer expired, check availability again")
        if not _is_free(c, off["room_id"], off["date"], _t(off["start_time"]), _t(off["end_time"])):
            raise HTTPException(409, "slot was just taken")
        bid = "BK-" + secrets.token_hex(3).upper()
        now = dt.datetime.now(IST).isoformat(timespec="seconds")
        claimed = {"id": bid, "customer_id": body.customer_id, "room_id": off["room_id"],
                   "date": off["date"], "start_time": off["start_time"],
                   "end_time": off["end_time"], "price_inr": off["price_inr"],
                   "status": "confirmed", "idempotency_key": idempotency_key, "created_at": now}
        if mode == "ghost":
            return claimed  # says it worked. it didn't.
        stored = dict(claimed)
        if mode == "wrong_room":
            other = c.execute("SELECT id FROM rooms WHERE id!=? ORDER BY capacity LIMIT 1",
                              (off["room_id"],)).fetchone()
            stored["room_id"] = other["id"]
        if mode == "pending":
            stored["status"] = "pending_payment"
        c.execute("INSERT INTO bookings VALUES (?,?,?,?,?,?,?,?,?,?)",
                  tuple(stored[k] for k in ("id", "customer_id", "room_id", "date",
                        "start_time", "end_time", "price_inr", "status",
                        "idempotency_key", "created_at")))
    if mode == "slow":
        time.sleep(6)
    return claimed


@app.get("/bookings/{booking_id}")
def get_booking(booking_id: str):
    with _lock, _conn() as c:
        row = c.execute("SELECT * FROM bookings WHERE id=?", (booking_id,)).fetchone()
    if not row:
        raise HTTPException(404, "booking not found")
    return dict(row)


@app.get("/bookings")
def find_bookings(idempotency_key: str | None = None, customer_id: str | None = None):
    q, args = "SELECT * FROM bookings WHERE 1=1", []
    if idempotency_key:
        q += " AND idempotency_key=?"; args.append(idempotency_key)
    if customer_id:
        q += " AND customer_id=?"; args.append(customer_id)
    with _lock, _conn() as c:
        return [dict(r) for r in c.execute(q + " ORDER BY created_at", args).fetchall()]


# ---------------------------------------------------------------- admin
class ChaosIn(BaseModel):
    mode: str


@app.post("/admin/chaos")
def set_chaos(body: ChaosIn):
    if body.mode not in CHAOS_MODES:
        raise HTTPException(422, f"mode must be one of {CHAOS_MODES}")
    _state["chaos"] = body.mode
    return {"chaos": body.mode}


@app.post("/admin/reset")
def admin_reset():
    reset_db()
    return {"ok": True}


@app.get("/admin/state")
def admin_state():
    with _lock, _conn() as c:
        rows = c.execute(
            "SELECT b.*, r.name AS room, cu.name AS customer FROM bookings b "
            "JOIN rooms r ON r.id=b.room_id JOIN customers cu ON cu.id=b.customer_id "
            "ORDER BY b.date, b.start_time"
        ).fetchall()
    return {"chaos": _state["chaos"], "bookings": [dict(r) for r in rows]}


